import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const builds = await Promise.all([
  build({ entryPoints: ['src/extension.ts'], bundle: true, platform: 'node',
    format: 'cjs', mainFields: ['module', 'main'], target: 'node20',
    external: ['vscode'], outfile: 'dist/extension.cjs', metafile: true }),
  build({ entryPoints: ['src/webview.ts'], bundle: true, platform: 'browser',
    outfile: 'dist/webview.js', metafile: true }),
  build({ entryPoints: ['src/skill-webview.ts'], bundle: true, platform: 'browser',
    outfile: 'dist/skill-webview.js', metafile: true })
]);

const packages = new Set();
for (const result of builds) {
  for (const input of Object.keys(result.metafile.inputs)) {
    const parts = input.split('/');
    const index = parts.lastIndexOf('node_modules');
    if (index >= 0) packages.add(parts.slice(0, index + (parts[index + 1].startsWith('@') ? 3 : 2)).join('/'));
  }
}
const notices = ['Third-party licenses for code bundled into Skill Editor.\nGenerated by esbuild.mjs from the installed, locked dependencies.\n'];
for (const directory of [...packages].sort()) {
  const manifest = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  const files = await readdir(directory);
  const license = files.find(file => /^(?:licen[sc]e|copying)(?:[-.].+)?$/i.test(file));
  if (!license) throw new Error(`Missing bundled dependency license: ${manifest.name}`);
  const text = (await readFile(join(directory, license), 'utf8')).replaceAll('\r\n', '\n').trim();
  notices.push(`\n===== ${manifest.name} ${manifest.version} (${manifest.license}) =====\n\n${text}\n`);
}
await writeFile('THIRD_PARTY_NOTICES.txt', notices.join(''));
